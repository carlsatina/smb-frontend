                        <div class="ai-summary-text" v-html="renderedSummary"></div>
                        <p class="ai-summary-meta">Generated by {{ aiSummaryModel }} · for {{ aiSummaryDate }}</p>
                    </div>
                    <p v-else class="ai-summary-empty">Click “Generate summary” to get an AI recap of yesterday’s performance.</p>
