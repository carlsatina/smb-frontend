<script setup lang="ts">
import { computed, nextTick, ref } from 'vue';
import { RouterLink } from 'vue-router';
import { useStoreContextStore } from '@/stores/storeContext';
import { renderMarkdownLite } from '@/utils/markdownLite';
import {
    generateDailySummary,
    aiChat,
    generateReorderPlan,
    type AiChatMessage,
    type ReorderPlanResponse,
} from '@/api/ai';

const storeContext = useStoreContextStore();

const currentStoreLabel = computed(() => storeContext.currentStore?.name ?? 'this store');
const role = computed(() => storeContext.currentStore?.role);
const aiConfigured = computed(() => !!storeContext.currentStore?.aiApiKeySet);
const canConfigure = computed(() => role.value === 'OWNER' || role.value === 'ADMIN');
const canUseAiSummary = computed(() => role.value === 'OWNER' || role.value === 'ADMIN');
const canUseReorder = computed(() => role.value === 'OWNER' || role.value === 'ADMIN' || role.value === 'INVENTORY_MANAGER');
const hasAnyAccess = computed(() => canUseAiSummary.value || canUseReorder.value);

// --- Daily summary ---
const aiSummary = ref<string | null>(null);
const aiSummaryModel = ref('');
const aiSummaryDate = ref('');
const aiSummaryError = ref('');
const isGeneratingSummary = ref(false);
const renderedSummary = computed(() => (aiSummary.value ? renderMarkdownLite(aiSummary.value) : ''));

const generateSummary = async () => {
    const storeId = storeContext.currentStoreId;
    if (!storeId || isGeneratingSummary.value) return;
    isGeneratingSummary.value = true;
    aiSummaryError.value = '';
    try {
        const result = await generateDailySummary(storeId);
        aiSummary.value = result.summary;
        aiSummaryModel.value = result.model;
        aiSummaryDate.value = result.data.targetDate;
    } catch (error: any) {
        aiSummaryError.value = error?.body?.error?.message || 'Unable to generate the summary. Please try again.';
    } finally {
        isGeneratingSummary.value = false;
    }
};

// --- Ask your data chat ---
const chatMessages = ref<AiChatMessage[]>([]);
const chatInput = ref('');
const isChatting = ref(false);
const chatError = ref('');
const chatScrollRef = ref<HTMLElement | null>(null);
const chatSuggestions = [
    'How did sales compare to last week?',
    'Top 5 products this month',
    'Which products have the lowest margin?',
    'What needs reordering?',
];

const scrollChatToBottom = () => {
    nextTick(() => {
        if (chatScrollRef.value) chatScrollRef.value.scrollTop = chatScrollRef.value.scrollHeight;
    });
};

const sendMessage = async (text: string) => {
    const storeId = storeContext.currentStoreId;
    const trimmed = text.trim();
    if (!storeId || !trimmed || isChatting.value) return;
    chatError.value = '';
    chatMessages.value.push({ role: 'user', content: trimmed });
    chatInput.value = '';
    isChatting.value = true;
    scrollChatToBottom();
    try {
        const result = await aiChat(storeId, chatMessages.value.slice(-19));
        chatMessages.value.push({ role: 'assistant', content: result.reply });
    } catch (error: any) {
        chatError.value = error?.body?.error?.message || 'Unable to answer that right now. Please try again.';
    } finally {
        isChatting.value = false;
        scrollChatToBottom();
    }
};

const sendChat = () => sendMessage(chatInput.value);
const askSuggestion = (text: string) => sendMessage(text);
const clearChat = () => {
    chatMessages.value = [];
    chatError.value = '';
};

// --- Reorder suggestions ---
const reorderPlan = ref<ReorderPlanResponse['plan'] | null>(null);
const reorderNarrative = ref<string | null>(null);
const reorderNarrativeError = ref<string | null>(null);
const reorderModel = ref<string | null>(null);
const reorderError = ref('');
const isReordering = ref(false);

const daysClass = (days: number | null) => {
    if (days === null || days <= 3) return 'days-pill--crit';
    if (days <= 7) return 'days-pill--warn';
    return 'days-pill--ok';
};

const generateReorder = async () => {
    const storeId = storeContext.currentStoreId;
    if (!storeId || isReordering.value) return;
    isReordering.value = true;
    reorderError.value = '';
    try {
        const result = await generateReorderPlan(storeId);
        reorderPlan.value = result.plan;
        reorderNarrative.value = result.narrative;
        reorderNarrativeError.value = result.narrativeError;
        reorderModel.value = result.model;
    } catch (error: any) {
        reorderError.value = error?.body?.error?.message || 'Unable to build the reorder plan. Please try again.';
    } finally {
        isReordering.value = false;
    }
};
</script>

